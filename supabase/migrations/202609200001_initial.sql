insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types) values('question-images','question-images',true,2097152,array['image/png','image/jpeg','image/webp']) on conflict do nothing;
create policy question_images_read on storage.objects for select using(bucket_id='question-images');
create policy question_images_admin on storage.objects for all to authenticated using(bucket_id='question-images' and public.is_admin()) with check(bucket_id='question-images' and public.is_admin());
commit;
